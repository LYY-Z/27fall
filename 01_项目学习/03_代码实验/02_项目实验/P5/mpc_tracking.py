"""Nonlinear SLSQP teaching MPC. No collision constraints, no hardware."""
import argparse,csv
from pathlib import Path
import numpy as np
from scipy.optimize import minimize
from bicycle_model import bicycle_step,wrap_angle

DEFAULT_BOUNDS=dict(accel_min=-1.,accel_max=1.,speed_min=0.,speed_max=1.,steering_abs_max=.5,accel_rate_max=2.,steering_rate_max=1.)
def solve_tracking_mpc(state,reference,previous_control,wheelbase,dt,bounds):
    state=np.asarray(state,float);reference=np.asarray(reference,float);previous_control=np.asarray(previous_control,float)
    required=set(DEFAULT_BOUNDS)
    if set(bounds)!=required:raise ValueError("bounds must have the documented seven keys")
    if state.shape!=(4,) or reference.ndim!=2 or reference.shape[1]!=4 or len(reference)<2 or previous_control.shape!=(2,):raise ValueError("state[4], reference[N+1,4], previous_control[2] required")
    if not np.all(np.isfinite(np.r_[state,reference.ravel(),previous_control,list(bounds.values()),wheelbase,dt])) or wheelbase<=0 or dt<=0:raise ValueError("finite data and positive L/dt required")
    b=bounds
    if b["accel_min"]>b["accel_max"] or b["speed_min"]>b["speed_max"] or not 0<b["steering_abs_max"]<np.pi/2 or min(b["accel_rate_max"],b["steering_rate_max"])<=0:raise ValueError("invalid bounds")
    n=len(reference)-1;lower=np.array([b["accel_min"],-b["steering_abs_max"]]);upper=np.array([b["accel_max"],b["steering_abs_max"]])
    if np.any(previous_control<lower) or np.any(previous_control>upper) or not b["speed_min"]<=state[3]<=b["speed_max"]:
        return np.full((n,2),np.nan),"invalid_initial_or_previous_control"
    rate=np.array([b["accel_rate_max"],b["steering_rate_max"]])*dt
    Q=np.diag([10.,10.,5.,1.]);R=np.diag([.1,.1])
    def predict(flat):
        controls=flat.reshape(n,2);states=[state]
        for control in controls:states.append(bicycle_step(states[-1],control,wheelbase,dt))
        return controls,np.array(states)
    def objective(flat):
        controls,states=predict(flat);error=states-reference;error[:,2]=wrap_angle(error[:,2])
        return float(sum(error[i]@Q@error[i]+controls[i]@R@controls[i] for i in range(n))+error[-1]@Q@error[-1])
    def constraints(flat):
        controls,states=predict(flat);change=np.diff(np.vstack([previous_control,controls]),axis=0)
        return np.r_[states[1:,3]-b["speed_min"],b["speed_max"]-states[1:,3],(rate-change).ravel(),(rate+change).ravel()]
    initial=np.tile(previous_control,(n,1)).ravel()
    result=minimize(objective,initial,method="SLSQP",bounds=list(zip(np.tile(lower,n),np.tile(upper,n))),constraints=[{"type":"ineq","fun":constraints}],options={"maxiter":100,"ftol":1e-6})
    valid=(result.success and np.all(np.isfinite(result.x))
           and np.all(result.x>=np.tile(lower,n)-1e-5)
           and np.all(result.x<=np.tile(upper,n)+1e-5)
           and np.all(np.isfinite(predict(result.x)[1]))
           and np.min(constraints(result.x))>=-1e-5)
    if not valid:return np.full((n,2),np.nan),"optimization_failed:"+str(result.message)
    return result.x.reshape(n,2),"success"
def main():
    p=argparse.ArgumentParser();p.add_argument("--out-dir",type=Path,required=True);a=p.parse_args();a.out_dir.mkdir(parents=True,exist_ok=True)
    dt=.1;n=8;state=np.array([0.,-.2,0.,.4]);previous=np.zeros(2)
    # Reference is generated by the SAME teaching model, not a real vehicle trajectory.
    reference_all=[np.array([0.,0.,0.,.4])]
    for k in range(100+n):reference_all.append(bicycle_step(reference_all[-1],[0.,.15],.5,dt))
    with (a.out_dir/"mpc_tracking.csv").open("w",newline="",encoding="utf-8") as f:
        w=csv.writer(f);w.writerow(["time_s","x_m","y_m","yaw_rad","speed_m_s","reference_x_m","reference_y_m","accel_m_s2","steering_rad","status"])
        for k in range(50):
            ref=np.array(reference_all[k:k+n+1]);plan,status=solve_tracking_mpc(state,ref,previous,.5,dt,DEFAULT_BOUNDS)
            if status=="success":control=plan[0]
            else:
                # Fault braking may violate normal rate limits; explicitly separated.
                control=np.array([DEFAULT_BOUNDS["accel_min"],previous[1]])
                control[0]=max(control[0],-state[3]/dt)
            # Next cycle must refer to the command actually applied, including fallback.
            previous=control.copy()
            w.writerow([k*dt,*state,*ref[0,:2],*control,status]);state=bicycle_step(state,control,.5,dt);state[3]=max(0.,state[3])
    print(a.out_dir)
if __name__=="__main__":main()
